alter table public.calc_logs     enable row level security;

-- profiles: each user reads only their own row. No insert/update policies:
-- rows are created by the trigger above, and users cannot change their role.
create policy "Allow users to read their own profile" on public.profiles
  for select to authenticated using ((select auth.uid()) = id);

-- price_table: readable by everyone (used by the calculator)
create policy "public read price_table" on public.price_table
  for select to anon, authenticated using (true);

-- calc_logs: signed-in users save calculations; only admins read/update/delete
create policy "calc_logs insert by signed-in users" on public.calc_logs
  for insert to authenticated with check (true);
create policy "calc_logs admin read" on public.calc_logs
  for select to authenticated using ((select private.is_admin()));
create policy "calc_logs admin update" on public.calc_logs
  for update to authenticated using ((select private.is_admin())) with check ((select private.is_admin()));
create policy "calc_logs admin delete" on public.calc_logs
  for delete to authenticated using ((select private.is_admin()));

-- Song catalog: admin-only for read and write
do $$
declare t text;
begin
  foreach t in array array['songs','artists','authors','genres','keywords',
                           'song_artists','song_authors','song_genres','song_keywords'] loop
    execute format('create policy "%s admin read" on public.%I for select to authenticated using ((select private.is_admin()))', t, t);
    execute format('create policy "%s admin insert" on public.%I for insert to authenticated with check ((select private.is_admin()))', t, t);
    execute format('create policy "%s admin update" on public.%I for update to authenticated using ((select private.is_admin())) with check ((select private.is_admin()))', t, t);
    execute format('create policy "%s admin delete" on public.%I for delete to authenticated using ((select private.is_admin()))', t, t);
  end loop;
end $$;
