-- Captured 2026-10-10 from the live database, after the access-control and catalog cleanup changes.
--
-- This file describes the database as it already exists. It has NOT been run against
-- production and must not be: production is already in this state. Use it to rebuild
-- the schema in a new/empty project, and add every future change as a new, later-dated
-- file in this folder.
--
-- Not included: data, the auth/storage schemas managed by Supabase, and the
-- backup_20261010 snapshot schema.

-- ============================================================
-- Extensions
-- ============================================================
create extension if not exists pgcrypto with schema extensions;
create extension if not exists "uuid-ossp" with schema extensions;
create extension if not exists pg_stat_statements with schema extensions;
create extension if not exists vector with schema public;

-- ============================================================
-- Admin helper
-- ============================================================
create schema if not exists private;
grant usage on schema private to anon, authenticated;

-- ============================================================
-- Tables
-- ============================================================
create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  updated_at timestamptz,
  username text,
  full_name text,
  role text,
  phone text,
  company text
);

create table public.songs (
  id integer generated by default as identity primary key,
  title text,
  lyrics text,
  is_free boolean default false,
  score text,
  year integer constraint songs_year_range check (year >= 1500 and year <= 2100),
  link text,
  is_free_tags text,
  year_nicks text,
  concept_desc text,
  mood text[],
  tags text[],
  embedding vector(1536)
);

create table public.artists (
  id serial primary key,
  name text not null
);

create table public.authors (
  id serial primary key,
  name text not null
);

create table public.genres (
  id serial primary key,
  name text not null
);

create table public.keywords (
  id serial primary key,
  name text not null
);

create table public.song_artists (
  song_id integer not null references public.songs(id) on delete cascade,
  artist_id integer not null references public.artists(id) on delete cascade,
  primary key (song_id, artist_id)
);

create table public.song_authors (
  song_id integer not null references public.songs(id) on delete cascade,
  author_id integer not null references public.authors(id) on delete cascade,
  primary key (song_id, author_id)
);

create table public.song_genres (
  song_id integer not null references public.songs(id) on delete cascade,
  genre_id integer not null references public.genres(id) on delete cascade,
  primary key (song_id, genre_id)
);

create table public.song_keywords (
  song_id integer not null references public.songs(id) on delete cascade,
  keyword_id integer not null references public.keywords(id) on delete cascade,
  primary key (song_id, keyword_id)
);

create table public.song_usages (
  id bigserial primary key,
  song_id integer not null references public.songs(id) on delete cascade,
  use_case text,
  brand text,
  product text,
  industry text,
  region text,
  year integer,
  duration_sec integer,
  brief text,
  rationale text,
  tags text[],
  link text,
  kpis jsonb,
  rationale_embedding vector(1536)
);

create table public.price_table (
  id serial primary key,
  license_type text,
  media_type text,
  territory text,
  level_1 integer,
  level_2 integer,
  level_3 integer,
  level_4 integer,
  vat_amount integer
);

create table public.calc_logs (
  id uuid primary key default gen_random_uuid(),
  name text,
  phone text,
  company text,
  email text,
  composition_name text,
  media text,
  production_type text,
  usage_duration_seconds integer,
  territory text,
  calculated_at timestamptz default now(),
  total numeric,
  contacted boolean default false
);

